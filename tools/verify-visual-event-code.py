"""Validate exported event fixtures with a real project's preprocessor and ARM macros.

Run the tests/visualevent_tests.pro executable with the project path as its first
positional argument first, then pass its build directory with --test-build.
Everything generated by this check stays in the test build directory.
"""
from pathlib import Path
import argparse
import os
import subprocess

parser = argparse.ArgumentParser()
parser.add_argument('--project', type=Path, required=True)
parser.add_argument('--test-build', type=Path, required=True)
parser.add_argument('--poryscript', type=Path, required=True)
parser.add_argument('--mingw', type=Path, default=Path('C:/Qt/Tools/mingw1310_64/bin'))
parser.add_argument('--arm-tools', type=Path, default=Path('C:/devkitPro/devkitARM/bin'))
args = parser.parse_args()
project = args.project.resolve()
build = args.test_build.resolve()
results = build / 'results'
results.mkdir(exist_ok=True, parents=True)
env = dict(os.environ)
env['PATH'] = str(args.mingw) + os.pathsep + env.get('PATH', '')

def run(command, *, cwd=build, data=None):
    result = subprocess.run([x.as_posix() if isinstance(x, Path) else str(x) for x in command], cwd=cwd, input=data,
                            stdout=subprocess.PIPE, stderr=subprocess.PIPE, env=env, timeout=90)
    if result.returncode:
        raise RuntimeError(f'{command[0]} failed ({result.returncode}):\n' + result.stderr.decode('utf-8', 'replace')[-8000:])
    return result.stdout

source = project / 'tools/preproc'
preproc = build / 'preproc-validation.exe'
files = ['asm_file.cpp', 'c_file.cpp', 'charmap.cpp', 'preproc.cpp', 'string_parser.cpp', 'utf8.cpp', 'io.cpp']
run([args.mingw/'g++.exe', '-std=c++11', '-O2', *(source/f for f in files), '-o', preproc])
poryroot = args.poryscript.resolve().parent
run([args.poryscript, '-i', results/'visual.pory', '-o', results/'from-pory.inc',
     '-cc', poryroot/'command_config.json', '-fc', poryroot/'font_config.json', '-lm=false'])

# Use the project's own headers and macro prelude; do not invent opcode values.
main = (project/'data/event_scripts.s').read_text(encoding='utf-8')
prelude = main[:main.index('.section script_data')]
for stem in ['visual', 'from-pory']:
    script = (results/(stem+'.inc')).read_text(encoding='utf-8')
    wrapper = results/(stem+'-wrapper.s')
    wrapper.write_text(prelude + '\n.section visual_event_test, "a", %progbits\n' + script, encoding='utf-8')
    first = run([preproc, wrapper, project/'charmap.txt'], cwd=project)
    cpp = run([args.arm_tools/'arm-none-eabi-cpp.exe', '-I', project/'include', '-I', project,
               '-DMODERN=1', '-DTESTING=0', '-DEMERALD', '-x', 'assembler-with-cpp', '-'], cwd=project, data=first)
    assembly = run([preproc, '-ie', wrapper, project/'charmap.txt'], cwd=project, data=cpp)
    asmfile = results/(stem+'-preprocessed.s')
    asmfile.write_bytes(assembly)
    run([args.arm_tools/'arm-none-eabi-as.exe', '-mcpu=arm7tdmi', '-march=armv4t', '-meabi=5',
         '--defsym', 'MODERN=1', '--defsym', 'EMERALD=1', '-o', results/(stem+'.o'), asmfile], cwd=project)
    print(f'PASS: {stem} -> project charmap/preproc -> ARM object ({(results/(stem+".o")).stat().st_size} bytes)')
(results/'toolchain-results.txt').write_text('PASS: generated .inc and Poryscript-compiled .inc both assembled with real project headers, charmap and event macros.\n', encoding='utf-8')
